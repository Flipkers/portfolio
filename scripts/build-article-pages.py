#!/usr/bin/env python3
"""Write one HTML file per case, launch, and test.

GitHub Pages serves a single case.html for every ?id=, and link previews
read that file without running the page script. Each article file below
carries that item's title, summary, and cover in the document head.

Re-run after editing data/cases.json, data/launches.json, or data/tests.json.
"""

import json
import os
import re
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGIN = "https://flipkers.github.io/portfolio"
ID_RE = re.compile(r"^[a-z0-9-]+$")
MARKER_RE = re.compile(r"/\* article-ids \*/[\s\S]*?/\* /article-ids \*/")

EARLY_LANG = """<script>
(function () {
  var lang = "ru";
  try { lang = localStorage.getItem("portfolio-lang") || "ru"; } catch (e) {}
  if (lang !== "en") return;
  var root = document.documentElement;
  var title = root.getAttribute("data-title-en");
  var description = root.getAttribute("data-description-en");
  if (title) document.title = title;
  var nodes = document.getElementsByTagName("meta");
  for (var i = 0; i < nodes.length; i++) {
    var node = nodes[i];
    if (node.getAttribute("name") === "description" && description) node.content = description;
    if (node.getAttribute("property") === "og:title" && title) node.content = title;
    if (node.getAttribute("property") === "og:description" && description) node.content = description;
    if (node.getAttribute("property") === "og:locale") node.content = "en_US";
  }
  root.lang = "en";
})();
</script>"""


def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as handle:
        return json.load(handle)


def esc(value):
    return (
        str(value)
        .replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def absolute_image(path):
    return ORIGIN + "/" + quote(path.lstrip("/"), safe="/")


def text(item, field, lang):
    value = (item.get(f"{field}_{lang}") or "").strip()
    if value:
        return value
    return (item.get(f"{field}_ru") or item.get(f"{field}_en") or "").strip()


def render(item, kind, name_ru, name_en):
    title_ru = text(item, "title", "ru")
    title_en = text(item, "title", "en")
    summary_ru = text(item, "summary", "ru") or title_ru
    summary_en = text(item, "summary", "en") or title_en
    doc_title_ru = f"{title_ru} — {name_ru}"
    doc_title_en = f"{title_en} — {name_en}"
    image = item.get("image") or ""
    if not image:
        raise SystemExit(f"{item['id']} has no cover")
    image_path = os.path.join(ROOT, image)
    if not os.path.isfile(image_path):
        raise SystemExit(f"missing cover for {item['id']}: {image}")

    back = "../index.html#tests" if kind == "test" else "../index.html"
    body_class = "case-page test-page" if kind == "test" else "case-page"
    return f"""<!DOCTYPE html>
<!-- Generated by scripts/build-article-pages.py. Re-run it after catalog edits. -->
<html lang="ru" data-title-en="{esc(doc_title_en)}" data-description-en="{esc(summary_en)}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
  <meta name="description" content="{esc(summary_ru)}">
  <title>{esc(doc_title_ru)}</title>
  <meta property="og:title" content="{esc(doc_title_ru)}">
  <meta property="og:description" content="{esc(summary_ru)}">
  <meta property="og:image" content="{esc(absolute_image(image))}">
  <meta property="og:type" content="article">
  <meta property="og:locale" content="ru_RU">
  {EARLY_LANG}
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <meta http-equiv="Cache-Control" content="no-cache">
  <link rel="stylesheet" href="../style.css?v=26">
</head>
<body class="{body_class}" data-root="../" data-article-id="{esc(item['id'])}">
  <header>
    <nav>
      <div class="nav-links">
        <a href="{back}" data-i18n="case.back">← К портфолио</a>
      </div>
      <button id="lang-toggle" type="button" aria-label="Switch language">EN</button>
    </nav>
  </header>

  <main>
    <article id="case-article" class="case-article" aria-live="polite">
      <p class="case-loading" data-i18n="case.loading">Загрузка…</p>
    </article>
  </main>

  <script src="../main.js?v=16"></script>
</body>
</html>
"""


def write_dir(directory, items, kind, name_ru, name_en):
    folder = os.path.join(ROOT, directory)
    os.makedirs(folder, exist_ok=True)
    keep = set()
    for item in items:
        item_id = item["id"]
        if not ID_RE.match(item_id):
            raise SystemExit(f"unsafe id: {item_id}")
        name = item_id + ".html"
        keep.add(name)
        path = os.path.join(folder, name)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(render(item, kind, name_ru, name_en))
        print(path)
    for name in os.listdir(folder):
        if name.endswith(".html") and name not in keep:
            os.remove(os.path.join(folder, name))
            print("removed", os.path.join(folder, name))


def write_ids(filename, ids, folder):
    path = os.path.join(ROOT, filename)
    with open(path, encoding="utf-8") as handle:
        html = handle.read()
    listed = ", ".join(json.dumps(item_id) for item_id in sorted(ids))
    replacement = f"/* article-ids */{listed}/* /article-ids */"
    updated, count = MARKER_RE.subn(replacement, html, count=1)
    if count != 1:
        raise SystemExit(f"no article-ids marker in {filename}")
    target = f'location.replace("{folder}/"'
    if target not in updated:
        raise SystemExit(f"redirect target missing in {filename}")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(updated)


def main():
    os.chdir(ROOT)
    profile = load("profile.json")
    name_ru = profile["meta"]["name"]
    name_en = profile["meta"]["name_en"]
    cases = load("cases.json")
    launches = load("launches.json")
    tests = load("tests.json")
    case_ids = [item["id"] for item in cases + launches]
    test_ids = [item["id"] for item in tests]
    overlap = set(case_ids) & set(test_ids)
    if overlap or len(case_ids) != len(set(case_ids)):
        raise SystemExit(f"duplicate article ids: {sorted(overlap or case_ids)}")
    write_dir("case", cases + launches, "case", name_ru, name_en)
    write_dir("test", tests, "test", name_ru, name_en)
    write_ids("case.html", case_ids, "case")
    write_ids("test.html", test_ids, "test")


if __name__ == "__main__":
    main()
